-- 0014: tokens Expo y borrado de actividades
create table if not exists public.push_tokens (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  expo_push_token text not null unique,
  platform text not null default 'unknown',
  updated_at timestamptz not null default now()
);
create index if not exists push_tokens_user_idx on public.push_tokens(user_id);
alter table public.push_tokens enable row level security;
drop policy if exists push_tokens_select_own on public.push_tokens;
create policy push_tokens_select_own on public.push_tokens for select to authenticated using (user_id = auth.uid());
drop policy if exists push_tokens_insert_own on public.push_tokens;
create policy push_tokens_insert_own on public.push_tokens for insert to authenticated with check (user_id = auth.uid());
drop policy if exists push_tokens_update_own on public.push_tokens;
create policy push_tokens_update_own on public.push_tokens for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists push_tokens_delete_own on public.push_tokens;
create policy push_tokens_delete_own on public.push_tokens for delete to authenticated using (user_id = auth.uid());
grant select, insert, update, delete on table public.push_tokens to authenticated;
grant usage, select on sequence public.push_tokens_id_seq to authenticated;
drop policy if exists activities_delete_recipient on public.activities;
create policy activities_delete_recipient on public.activities for delete to authenticated using (recipient_id = auth.uid());

-- 0015: búsqueda de perfiles públicos
alter table public.profiles add column if not exists username text;
create unique index if not exists profiles_username_lower_unique
on public.profiles (lower(username))
where username is not null and length(trim(username)) > 0;
create or replace function public.search_public_profiles(p_query text)
returns table (id uuid, name text, username text, avatar_url text, cover_url text, bio text)
language sql security definer set search_path = public
as $$
  select p.id, p.name, p.username, p.avatar_url, p.cover_url, p.bio
  from public.profiles p
  where p.id <> auth.uid()
    and coalesce(p.is_public, false) = true
    and length(trim(coalesce(p_query, ''))) >= 2
    and (
      lower(coalesce(p.username, '')) like '%' || lower(trim(p_query)) || '%'
      or lower(coalesce(p.name, '')) like '%' || lower(trim(p_query)) || '%'
      or lower(coalesce(p.email, '')) like '%' || lower(trim(p_query)) || '%'
    )
  order by lower(coalesce(p.name, p.username, ''))
  limit 25;
$$;
grant execute on function public.search_public_profiles(text) to authenticated;

-- 0016: textos de actividad sin revelar el nombre del lugar
create or replace function public.create_activity_from_checkin()
returns trigger language plpgsql security definer set search_path = public
as $$
declare action_type text;
begin
  if tg_op = 'INSERT' then action_type := 'check_in';
  elsif old.status = 'active' and new.status = 'ended' then action_type := 'check_out';
  else return new;
  end if;
  insert into public.activities (recipient_id, actor_id, type, checkin_id, venue_id, message)
  select case when f.user_id = new.user_id then f.friend_id else f.user_id end,
    new.user_id, action_type, new.id, new.venue_id,
    case when action_type = 'check_in' then 'está tomando algo' else 'ha terminado su visita' end
  from public.friendships f
  where f.status = 'accepted' and (f.user_id = new.user_id or f.friend_id = new.user_id)
  on conflict (recipient_id, checkin_id, type) do nothing;
  return new;
end;
$$;

-- 0017: solicitudes de amistad con acciones en la notificación
alter table public.activities add column if not exists friendship_id bigint references public.friendships(id) on delete cascade;
create index if not exists activities_friendship_idx on public.activities(friendship_id);
create or replace function public.create_activity_from_friend_request()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if new.status <> 'pending' then return new; end if;
  insert into public.activities (recipient_id, actor_id, type, friendship_id, checkin_id, venue_id, message)
  values (new.friend_id, new.user_id, 'friend_request', new.id, null, null, 'te envió una solicitud de amistad');
  return new;
end;
$$;
drop trigger if exists friendships_friend_request_activity on public.friendships;
create trigger friendships_friend_request_activity
after insert on public.friendships for each row
execute function public.create_activity_from_friend_request();

