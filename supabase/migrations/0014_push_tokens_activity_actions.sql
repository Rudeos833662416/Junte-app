-- Tokens Expo por usuario para notificaciones push fuera de la aplicación.
create table if not exists public.push_tokens (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  expo_push_token text not null unique,
  platform text not null default 'unknown',
  updated_at timestamptz not null default now()
);

create index if not exists push_tokens_user_idx on public.push_tokens(user_id);
alter table public.push_tokens enable row level security;

drop policy if exists push_tokens_select_own on public.push_tokens;
create policy push_tokens_select_own on public.push_tokens
for select to authenticated using (user_id = auth.uid());

drop policy if exists push_tokens_insert_own on public.push_tokens;
create policy push_tokens_insert_own on public.push_tokens
for insert to authenticated with check (user_id = auth.uid());

drop policy if exists push_tokens_update_own on public.push_tokens;
create policy push_tokens_update_own on public.push_tokens
for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists push_tokens_delete_own on public.push_tokens;
create policy push_tokens_delete_own on public.push_tokens
for delete to authenticated using (user_id = auth.uid());

grant select, insert, update, delete on table public.push_tokens to authenticated;
grant usage, select on sequence public.push_tokens_id_seq to authenticated;

-- Actividad: permitir borrar una notificación propia desde el gesto de deslizamiento.
drop policy if exists activities_delete_recipient on public.activities;
create policy activities_delete_recipient on public.activities
for delete to authenticated using (recipient_id = auth.uid());
